// PhD-grade deep-research engine, running fully locally on Gemma.
//
// Pipeline (strict input boundaries — agents cannot influence each other):
//   1. ORCHESTRATOR  restates the question and decomposes it into 3–7
//                    sub-questions. It performs no research itself.
//   2. RESEARCHERS   one ISOLATED pass per sub-question: each sees only its
//                    sub-question (+ real OrioSearch results when enabled) —
//                    never the other agents' work. Facts + citations + gaps.
//   3. ANALYST       sees only the Researchers' notes. Synthesizes insights,
//                    models/frameworks, implications, uncertainties.
//   4. CRITIC        sees Researcher + Analyst outputs plus the machine-built
//                    list of VERIFIED sources. Adversarial review + verdict.
//   5. REVISION      if the Critic's verdict is MAJOR_ISSUES, the Orchestrator
//                    relays the required corrections to the Analyst (bounded
//                    cycles), then the Critic re-reviews.
//   6. ORCHESTRATOR  integrates everything into the final structured report.
//
// Anti-hallucination protocol:
//   • Every agent is instructed: no invented facts/URLs; mark UNKNOWN /
//     UNVERIFIED explicitly; reason internally but output only conclusions.
//   • MECHANICAL citation verification: the app records every URL OrioSearch
//     actually returned (the "evidence ledger"). Cited URLs are checked
//     against it in code — an LLM never "verifies" anything on trust.
//   • The final References section is assembled by code from the ledger
//     (only real, cited sources), never generated by the model.

